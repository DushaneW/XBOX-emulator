"""Generates KernelExports.g.cs from nxdk's lib/xboxkrnl/xboxkrnl.exe.def (CC0-1.0).
Usage: python tools/gen/gen_kernel_exports.py <path-to-xboxkrnl.exe.def> <output.cs>"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
rows = []
for line in open(src, encoding='utf-8'):
    m = re.match(r'\s+(@?)([A-Za-z_][A-Za-z0-9_]*)(@(\d+))?\s+@\s*(\d+)\s+NONAME(\s+DATA)?', line)
    if not m: continue
    fast, name, _, argbytes, ordinal, data = m.groups()
    kind = 'Data' if data else ('Fastcall' if fast else ('Stdcall' if argbytes is not None else 'Cdecl'))
    rows.append((int(ordinal), name, kind, int(argbytes or 0)))
rows.sort()
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// <auto-generated> from nxdk lib/xboxkrnl/xboxkrnl.exe.def (CC0-1.0) by tools/gen/gen_kernel_exports.py. Do not edit.\n')
    f.write('namespace XboxPc.Emulation.OriginalXbox;\n\n')
    f.write('public enum KernelExportKind { Stdcall, Cdecl, Fastcall, Data }\n\n')
    f.write('public sealed record KernelExportInfo(int Ordinal, string Name, KernelExportKind Kind, int ArgumentBytes);\n\n')
    f.write('public static class KernelExports\n{\n')
    f.write(f'    public const int Count = {len(rows)};\n\n')
    f.write('    public static readonly IReadOnlyDictionary<int, KernelExportInfo> ByOrdinal = new Dictionary<int, KernelExportInfo>\n    {\n')
    for o, n, k, a in rows:
        f.write(f'        [{o}] = new({o}, "{n}", KernelExportKind.{k}, {a}),\n')
    f.write('    };\n}\n')
print(f'{len(rows)} exports')
